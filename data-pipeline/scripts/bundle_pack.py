#!/usr/bin/env python3
"""
Bundle a data pack into the app's assets so it ships inside the APK.

Metro cannot glob a directory, so each pack file needs an explicit require().
This script:
  1. copies the pack into app/assets/packs/data-pack-<region>/
  2. rewrites the bundled manifest.json so it declares only the files actually
     shipped (the app verifies every installed file against this manifest, so a
     manifest that lists excluded files would fail the integrity check)
  3. generates app/src/data/bundledPacks.generated.ts with the require() map
     and the asset-extension list Metro needs

Tiers
-----
  full  everything, including the base map and the elevation raster
  lite  towers + fiber + soil + population + configs, no map, no elevation.
        ~30 MB instead of ~245 MB — for budget devices and small downloads.
        The app degrades gracefully: the map screen reports that this pack has
        no basemap, and the line-of-sight engine falls back to a flat-earth
        profile with a clear note in the report.

Usage:
    python bundle_pack.py --region rajasthan --tier full
    python bundle_pack.py --region rajasthan --tier lite
"""
import argparse
import json
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
APP = os.path.join(ROOT, "app")
DIST_PACKS = os.path.join(ROOT, "dist", "packs")
ASSETS_PACKS = os.path.join(APP, "assets", "packs")
OUT_TS = os.path.join(APP, "src", "data", "bundledPacks.generated.ts")

# extensions Metro must treat as assets (added to metro.config.js)
ASSET_EXTS = ["pmtiles", "sqlite", "geojson"]

# files omitted from the lite tier, by pack-relative path
LITE_EXCLUDE = {
    "tiles/base-map.pmtiles",
    "elevation/elevation.tif",
}

# which raster/config files the lite tier keeps
TIER_DESC = {
    "full": "base map + elevation + all vectors",
    "lite": "vectors + population only (no base map, no elevation)",
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--region", default="rajasthan")
    ap.add_argument("--tier", default="full", choices=["full", "lite"])
    args = ap.parse_args()

    src = os.path.join(DIST_PACKS, f"data-pack-{args.region}")
    if not os.path.isdir(src):
        raise SystemExit(f"pack not found: {src}")

    dst = os.path.join(ASSETS_PACKS, f"data-pack-{args.region}")
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst)

    # Apply the tier: remove excluded files from the bundled copy.
    excluded = []
    if args.tier == "lite":
        for rel in LITE_EXCLUDE:
            p = os.path.join(dst, rel)
            if os.path.exists(p):
                os.remove(p)
                excluded.append(rel)
        # drop now-empty dirs
        for d in ("tiles", "elevation"):
            dd = os.path.join(dst, d)
            if os.path.isdir(dd) and not os.listdir(dd):
                os.rmdir(dd)

    # collect files relative to the pack root
    files = []
    for dirpath, _dirnames, filenames in os.walk(dst):
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, dst).replace(os.sep, "/")
            files.append((rel, os.path.getsize(full)))

    # Rewrite the bundled manifest so it declares only what actually shipped.
    # The app verifies each installed file against this manifest; leaving an
    # excluded file listed would fail the integrity check and block install.
    mpath = os.path.join(dst, "manifest.json")
    if os.path.exists(mpath):
        with open(mpath) as f:
            manifest = json.load(f)
        kept = {rel for rel, _sz in files}
        manifest["files"] = [f for f in manifest.get("files", []) if f["path"] in kept]
        manifest["tier"] = args.tier
        manifest["tier_description"] = TIER_DESC[args.tier]
        if excluded:
            manifest["excluded"] = sorted(excluded)
        # drop source_dates for datasets that are not shipped
        sd = manifest.get("source_dates")
        if sd:
            if args.tier == "lite":
                sd.pop("elevation", None)
                sd.pop("basemap", None)
        with open(mpath, "w") as f:
            json.dump(manifest, f, indent=2)
        # the manifest changed on disk, so refresh its recorded size
        files = [(rel, os.path.getsize(os.path.join(dst, rel))) for rel, _ in files]

    # require() paths are relative to src/data/
    def req_path(rel: str) -> str:
        return f"../../assets/packs/data-pack-{args.region}/{rel}"

    lines = [
        "// AUTO-GENERATED by data-pipeline/scripts/bundle_pack.py — do not edit.",
        "// Registers the data packs shipped inside the app.",
        "",
        "export interface BundledPack {",
        "  region: string;",
        "  tier: 'full' | 'lite';",
        "  files: Record<string, number>;",
        "}",
        "",
        "export const BUNDLED_PACKS: BundledPack[] = [",
        "  {",
        f"    region: {json.dumps(args.region)},",
        f"    tier: {json.dumps(args.tier)},",
        "    files: {",
    ]
    for rel, _sz in files:
        lines.append(f"      {json.dumps(rel)}: require({json.dumps(req_path(rel))}),")
    lines += ["    },", "  },", "];", ""]

    with open(OUT_TS, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    # Gradle caches generated res/react assets from the previous bundle and does
    # NOT remove entries for files that are no longer referenced. Switching
    # tier (or dropping a file) would otherwise ship the stale asset anyway —
    # a "lite" APK still carrying the 84 MB basemap. Clear them so the next
    # build reflects the assets on disk.
    stale_dirs = [
        os.path.join(APP, "android", "app", "build", "generated", "res", "react"),
        os.path.join(APP, "android", "app", "build", "intermediates", "packaged_res", "release"),
        os.path.join(APP, "android", "app", "build", "intermediates", "compressed_assets", "release"),
        os.path.join(APP, "android", "app", "build", "intermediates", "assets", "release"),
    ]
    cleared = []
    for d in stale_dirs:
        if os.path.isdir(d):
            shutil.rmtree(d)
            cleared.append(os.path.relpath(d, APP))
    if cleared:
        print(f"cleared {len(cleared)} stale gradle asset dir(s): {', '.join(cleared)}")

    total = sum(sz for _r, sz in files)
    print(f"bundled pack '{args.region}' tier={args.tier} -> {dst}")
    print(f"  files: {len(files)}   total: {total/1e6:.1f} MB")
    for rel, sz in files:
        print(f"    {rel:34s} {sz/1e6:7.1f} MB")
    if excluded:
        print(f"  excluded ({TIER_DESC[args.tier]}): {', '.join(excluded)}")
    print(f"wrote {OUT_TS}")
    print(f"asset extensions needed: {', '.join(ASSET_EXTS)}")


if __name__ == "__main__":
    main()
