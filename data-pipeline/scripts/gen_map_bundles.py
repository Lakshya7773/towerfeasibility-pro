#!/usr/bin/env python3
"""
Generate a TypeScript module that inlines the MapLibre GL JS, PMTiles and
font-glyph assets the offline WebView map needs.

Why inline: the offline map runs MapLibre GL JS inside a WebView and must never
touch the network. Bundling the JS + glyphs as base64/plain strings sidesteps
Metro asset-extension handling and any CDN dependency. MapView writes the HTML
to disk on first launch and loads it from there.

Usage:
    python gen_map_bundles.py
"""
import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.abspath(os.path.join(HERE, "..", "..", "app"))
ASSETS = os.path.join(APP, "assets", "map")
OUT = os.path.join(APP, "src", "components", "map", "mapBundles.generated.ts")

# glyph filename -> [fontstack, range] used by the MapLibre style
GLYPH_FONTS = {
    "Noto_Sans_Regular__0-255.pbf": ("Noto Sans Regular", "0-255"),
    "Noto_Sans_Regular__256-511.pbf": ("Noto Sans Regular", "256-511"),
    "Noto_Sans_Regular__512-767.pbf": ("Noto Sans Regular", "512-767"),
    "Noto_Sans_Devanagari_Regular__2304-2559.pbf": ("Noto Sans Devanagari Regular", "2304-2559"),
    "Noto_Sans_Devanagari_Regular__2560-2815.pbf": ("Noto Sans Devanagari Regular", "2560-2815"),
    "Noto_Sans_Devanagari_Regular__2816-3071.pbf": ("Noto Sans Devanagari Regular", "2816-3071"),
}


def read(name: str) -> str:
    with open(os.path.join(ASSETS, name), "r", encoding="utf-8") as f:
        return f.read()


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def main():
    maplibre = read("maplibre-gl.js")
    pmtiles = read("pmtiles.js")
    css = read("maplibre-gl.css")

    glyph_entries = []
    for fname, (font, rng) in GLYPH_FONTS.items():
        path = os.path.join(ASSETS, "glyphs", fname)
        if not os.path.exists(path):
            print(f"  WARN missing glyph {fname}")
            continue
        with open(path, "rb") as f:
            b64 = base64.b64encode(f.read()).decode("ascii")
        glyph_entries.append((font, rng, b64))

    lines = [
        "// AUTO-GENERATED by data-pipeline/scripts/gen_map_bundles.py — do not edit.",
        "// Inlined browser bundles + glyphs for the offline WebView map.",
        "",
        f"export const MAPLIBRE_JS = `{esc(maplibre)}`;",
        "",
        f"export const PMTILES_JS = `{esc(pmtiles)}`;",
        "",
        f"export const MAPLIBRE_CSS = `{esc(css)}`;",
        "",
        "/** Font glyph ranges as base64 PBF, keyed `<fontstack>/<range>` */",
        "export const GLYPHS: Record<string, string> = {",
    ]
    for font, rng, b64 in glyph_entries:
        key = f"{font}/{rng}"
        lines.append(f"  {json.dumps(key)}: {json.dumps(b64)},")
    lines.append("};")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"wrote {OUT}")
    print(f"  maplibre-gl.js : {len(maplibre)/1024:.0f} KB")
    print(f"  pmtiles.js     : {len(pmtiles)/1024:.0f} KB")
    print(f"  glyphs         : {len(glyph_entries)} ranges")
    print(f"  module size    : {os.path.getsize(OUT)/1024:.0f} KB")


if __name__ == "__main__":
    main()
